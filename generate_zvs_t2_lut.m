function [headerPath, sourcePath] = generate_zvs_t2_lut(matFile, outDir)
%GENERATE_ZVS_T2_LUT Export the normalized T2 map to C2000 C/H files.
%
%   generate_zvs_t2_lut
%   generate_zvs_t2_lut('ZVS_LUT.mat', '.')
%   [hFile, cFile] = generate_zvs_t2_lut(matFile, outDir)
%
% Run IL_opt_map_generate.m first, then call generate_zvs_t2_lut. By default,
% this function reads ZVS_LUT.mat and writes zvs_t2_lut.c/.h beside this file.
% Include zvs_t2_lut.h and compile zvs_t2_lut.c in the C2000 project.
%
% The MATLAB map stores T2_table as T2/Ts. The generated table stores the
% normalized T2 value directly as uint16_t fixed point: 0..65534 maps to
% 0..1, and 65535 is reserved for invalid map entries. This avoids a second
% T2 value array in Flash. The C lookup function accepts Vin, Vo and Icmd
% and returns normalized T2. Values outside an axis are clamped to its end.
% A seconds-valued API is also generated.

if nargin < 1 || isempty(matFile)
    thisFile = mfilename('fullpath');
    matFile = fullfile(fileparts(thisFile), 'ZVS_LUT.mat');
end
if nargin < 2 || isempty(outDir)
    outDir = fileparts(mfilename('fullpath'));
end

assert(ischar(matFile) || (isstring(matFile) && isscalar(matFile)), ...
    'matFile must be a character vector or scalar string.');
assert(ischar(outDir) || (isstring(outDir) && isscalar(outDir)), ...
    'outDir must be a character vector or scalar string.');
matFile = char(matFile);
outDir = char(outDir);
assert(exist(matFile, 'file') == 2, 'MAT file does not exist: %s', matFile);

S = load(matFile);
requiredFields = {'Vin_axis', 'Vo_axis', 'Icmd_axis', 'T2_table'};
for k = 1:numel(requiredFields)
    assert(isfield(S, requiredFields{k}), ...
        'MAT file is missing required variable ''%s''.', requiredFields{k});
end

vin = axisVector(S.Vin_axis, 'Vin_axis');
vo = axisVector(S.Vo_axis, 'Vo_axis');
icmd = axisVector(S.Icmd_axis, 'Icmd_axis');
T2 = double(S.T2_table);
expectedSize = [numel(vin), numel(vo), numel(icmd)];
actualSize = [size(T2, 1), size(T2, 2), size(T2, 3)];
assert(isequal(actualSize, expectedSize), ...
    'T2_table size must be [%d %d %d], but is [%s].', ...
    expectedSize(1), expectedSize(2), expectedSize(3), num2str(actualSize));
assert(numel(T2) == prod(expectedSize), ...
    'T2_table must contain exactly %d values.', prod(expectedSize));
assert(all(expectedSize <= double(intmax('uint16'))), ...
    'Each table dimension must fit in uint16_t.');
assert(numel(T2) <= double(intmax('uint32')), ...
    'The table is too large for a uint32_t flat index.');

Ts = getSwitchingPeriod(S);
valid = ~(isnan(T2) | isinf(T2));
if any(valid(:))
    validValues = T2(valid);
    assert(all(validValues >= -1.0e-7 & validValues <= 1.0 + 1.0e-7), ...
        'Finite T2_table values must be normalized T2/Ts in the range [0, 1].');
end

if ~exist(outDir, 'dir')
    mkdir(outDir);
end

headerPath = fullfile(outDir, 'zvs_t2_lut.h');
sourcePath = fullfile(outDir, 'zvs_t2_lut.c');
writeHeader(headerPath, vin, vo, icmd, Ts, S);
writeSource(sourcePath, vin, vo, icmd, T2);

invalidCount = sum(~valid(:));
fprintf('Generated %s\nGenerated %s\n', headerPath, sourcePath);
fprintf('Table size: %d x %d x %d (%d entries, %d invalid)\n', ...
    numel(vin), numel(vo), numel(icmd), numel(T2), invalidCount);
end

function values = axisVector(value, name)
assert(isnumeric(value) && isvector(value) && numel(value) >= 2, ...
    '%s must be a numeric vector with at least two points.', name);
values = double(value(:));
assert(~any(isnan(values) | isinf(values)), ...
    '%s contains NaN or Inf.', name);
assert(all(diff(values) > 0), '%s must be strictly increasing.', name);
end

function Ts = getSwitchingPeriod(S)
if isfield(S, 'Ts')
    Ts = double(S.Ts);
elseif isfield(S, 'fsw')
    fsw = double(S.fsw);
    assert(isscalar(fsw) && ~isnan(fsw) && ~isinf(fsw) && fsw > 0, ...
        'fsw must be a positive finite scalar.');
    Ts = 1.0 / fsw;
else
    error('MAT file must contain Ts or fsw.');
end
assert(isscalar(Ts) && ~isnan(Ts) && ~isinf(Ts) && Ts > 0, ...
    'Ts must be a positive finite scalar.');
end

function writeHeader(path, vin, vo, icmd, Ts, S)
fid = fopen(path, 'wt');
assert(fid >= 0, 'Cannot open header for writing: %s', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

fprintf(fid, '/* Generated by generate_zvs_t2_lut.m. Do not edit by hand. */\n');
fprintf(fid, '#ifndef ZVS_T2_LUT_H_\n#define ZVS_T2_LUT_H_\n\n');
fprintf(fid, '#include <stdint.h>\n\n');
fprintf(fid, '#ifdef __cplusplus\nextern "C" {\n#endif\n\n');
% Use UL so the product remains 32-bit on the C28x compiler, where int is
% 16 bits. The table has 41^3 entries in the default configuration.
fprintf(fid, '#define ZVS_T2_N_VIN             (%dUL)\n', numel(vin));
fprintf(fid, '#define ZVS_T2_N_VO              (%dUL)\n', numel(vo));
fprintf(fid, '#define ZVS_T2_N_ICMD            (%dUL)\n', numel(icmd));
fprintf(fid, '#define ZVS_T2_TABLE_SIZE        (ZVS_T2_N_VIN * ZVS_T2_N_VO * ZVS_T2_N_ICMD)\n');
fprintf(fid, '#define ZVS_T2_INVALID_CODE      (65535U)\n');
fprintf(fid, '#define ZVS_T2_VALUE_SCALE       (65534.0F)\n');
fprintf(fid, '#define ZVS_T2_INVALID           (-1.0F)\n\n');
fprintf(fid, '#define ZVS_T2_VIN_MIN_V         (%s)\n', cFloat(vin(1)));
fprintf(fid, '#define ZVS_T2_VIN_MAX_V         (%s)\n', cFloat(vin(end)));
fprintf(fid, '#define ZVS_T2_VO_MIN_V          (%s)\n', cFloat(vo(1)));
fprintf(fid, '#define ZVS_T2_VO_MAX_V          (%s)\n', cFloat(vo(end)));
fprintf(fid, '#define ZVS_T2_ICMD_MIN_A        (%s)\n', cFloat(icmd(1)));
fprintf(fid, '#define ZVS_T2_ICMD_MAX_A        (%s)\n', cFloat(icmd(end)));
fprintf(fid, '#define ZVS_T2_SWITCH_PERIOD_S   (%s)\n', cFloat(Ts));
if isfield(S, 'fsw')
    fsw = double(S.fsw);
    assert(isscalar(fsw) && ~isnan(fsw) && ~isinf(fsw) && fsw > 0, ...
        'fsw must be a positive finite scalar.');
    fprintf(fid, '#define ZVS_T2_SWITCH_FREQ_HZ    (%s)\n', cFloat(fsw));
end
if isfield(S, 'Coss')
    fprintf(fid, '#define ZVS_T2_COSS_F             (%s)\n', cFloat(double(S.Coss)));
end
if isfield(S, 'tdead')
    fprintf(fid, '#define ZVS_T2_DEADTIME_S         (%s)\n', cFloat(double(S.tdead)));
end
if isfield(S, 'L')
    fprintf(fid, '#define ZVS_T2_INDUCTANCE_H       (%s)\n', cFloat(double(S.L)));
end
if isfield(S, 'I0')
    fprintf(fid, '#define ZVS_T2_INITIAL_CURRENT_A  (%s)\n', cFloat(double(S.I0)));
end
if isfield(S, 'gTs')
    fprintf(fid, '#define ZVS_T2_SIM_STEP_S         (%s)\n', cFloat(double(S.gTs)));
end
fprintf(fid, '\n');
fprintf(fid, 'extern const float zvs_t2_vin_axis[ZVS_T2_N_VIN];\n');
fprintf(fid, 'extern const float zvs_t2_vo_axis[ZVS_T2_N_VO];\n');
fprintf(fid, 'extern const float zvs_t2_icmd_axis[ZVS_T2_N_ICMD];\n');
fprintf(fid, '/* Table cell code = round((T2/Ts) * ZVS_T2_VALUE_SCALE). */\n');
fprintf(fid, 'extern const uint16_t zvs_t2_table[ZVS_T2_TABLE_SIZE];\n\n');
fprintf(fid, '/* Return T2/Ts. Returns ZVS_T2_INVALID when no valid table value exists. */\n');
fprintf(fid, 'float ZVS_T2_Lookup(float vin_v, float vo_v, float icmd_a);\n');
fprintf(fid, '/* Return T2 in seconds. Returns ZVS_T2_INVALID on an invalid lookup. */\n');
fprintf(fid, 'float ZVS_T2_LookupSeconds(float vin_v, float vo_v, float icmd_a);\n');
fprintf(fid, '/* Read one table cell after bounds checking. Return value is T2/Ts. */\n');
fprintf(fid, 'float ZVS_T2_GetByIndex(uint16_t vin_index, uint16_t vo_index, uint16_t icmd_index);\n\n');
fprintf(fid, '#ifdef __cplusplus\n}\n#endif\n\n');
fprintf(fid, '#endif /* ZVS_T2_LUT_H_ */\n');
end

function writeSource(path, vin, vo, icmd, T2)
fid = fopen(path, 'wt');
assert(fid >= 0, 'Cannot open source for writing: %s', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

fprintf(fid, '/* Generated by generate_zvs_t2_lut.m. Do not edit by hand. */\n');
fprintf(fid, '#include "zvs_t2_lut.h"\n\n');
writeVector(fid, 'zvs_t2_vin_axis', vin);
writeVector(fid, 'zvs_t2_vo_axis', vo);
writeVector(fid, 'zvs_t2_icmd_axis', icmd);

fprintf(fid, '#ifdef ZVS_T2_USE_DATA_SECTION\n');
fprintf(fid, '#pragma DATA_SECTION(zvs_t2_table, "ZVS_T2_TABLE")\n');
fprintf(fid, '#pragma DATA_ALIGN(zvs_t2_table, 2)\n');
fprintf(fid, '#endif\n');
fprintf(fid, 'const uint16_t zvs_t2_table[ZVS_T2_TABLE_SIZE] = {\n');
% MATLAB is column-major. Permuting [3 2 1] makes Icmd the fastest C index.
valid = ~(isnan(T2) | isinf(T2));
codes = zeros(size(T2), 'uint16');
codes(valid) = uint16(round(min(max(T2(valid), 0.0), 1.0) * 65534.0));
codes(~valid) = uint16(65535);
values = permute(codes, [3 2 1]);
values = values(:);
for k = 1:numel(values)
    if values(k) == uint16(65535)
        fprintf(fid, '    ZVS_T2_INVALID_CODE');
    else
        fprintf(fid, '    %dU', values(k));
    end
    if k < numel(values)
        fprintf(fid, ',');
    end
    if mod(k, 8) == 0
        fprintf(fid, '\n');
    else
        fprintf(fid, ' ');
    end
end
fprintf(fid, '};\n\n');

fprintf(fid, 'static uint16_t zvs_t2_axis_index(float x, const float *axis,\n');
fprintf(fid, '                                     uint16_t n, float *fraction)\n{\n');
fprintf(fid, '    uint16_t low_index;\n    uint16_t high_index;\n    uint16_t mid;\n\n');
fprintf(fid, '    if (x <= axis[0]) { *fraction = 0.0F; return 0U; }\n');
fprintf(fid, '    if (x >= axis[n - 1U]) { *fraction = 1.0F; return (uint16_t)(n - 2U); }\n');
fprintf(fid, '    low_index = 0U;\n    high_index = (uint16_t)(n - 1U);\n');
fprintf(fid, '    while ((uint16_t)(high_index - low_index) > 1U) {\n');
fprintf(fid, '        mid = (uint16_t)(((uint32_t)low_index + (uint32_t)high_index) / 2UL);\n');
fprintf(fid, '        if (x < axis[mid]) high_index = mid;\n');
fprintf(fid, '        else low_index = mid;\n    }\n');
fprintf(fid, '    *fraction = (x - axis[low_index]) /\n');
fprintf(fid, '                 (axis[high_index] - axis[low_index]);\n');
fprintf(fid, '    return low_index;\n}\n\n');

fprintf(fid, 'static float zvs_t2_sample(uint16_t iv, uint16_t io, uint16_t ii)\n{\n');
fprintf(fid, '    uint32_t index;\n    uint16_t code;\n');
fprintf(fid, '    index = ((uint32_t)iv * (uint32_t)ZVS_T2_N_VO + (uint32_t)io) *\n');
fprintf(fid, '            (uint32_t)ZVS_T2_N_ICMD + (uint32_t)ii;\n');
fprintf(fid, '    code = zvs_t2_table[index];\n');
fprintf(fid, '    if (code == ZVS_T2_INVALID_CODE) return ZVS_T2_INVALID;\n');
fprintf(fid, '    return (float)code / ZVS_T2_VALUE_SCALE;\n}\n\n');

fprintf(fid, 'static void zvs_t2_accumulate(float value, float weight,\n');
fprintf(fid, '                               float *sum, float *weight_sum)\n{\n');
fprintf(fid, '    if ((weight > 0.0F) && (value != ZVS_T2_INVALID)) {\n');
fprintf(fid, '        *sum += value * weight;\n        *weight_sum += weight;\n    }\n}\n\n');

fprintf(fid, 'float ZVS_T2_GetByIndex(uint16_t vin_index, uint16_t vo_index,\n');
fprintf(fid, '                        uint16_t icmd_index)\n{\n');
fprintf(fid, '    if ((vin_index >= ZVS_T2_N_VIN) || (vo_index >= ZVS_T2_N_VO) ||\n');
fprintf(fid, '        (icmd_index >= ZVS_T2_N_ICMD)) return ZVS_T2_INVALID;\n');
fprintf(fid, '    return zvs_t2_sample(vin_index, vo_index, icmd_index);\n}\n\n');

fprintf(fid, 'float ZVS_T2_Lookup(float vin_v, float vo_v, float icmd_a)\n{\n');
fprintf(fid, '    uint16_t iv;\n    uint16_t io;\n    uint16_t ii;\n');
fprintf(fid, '    float fv;\n    float fo;\n    float fi;\n');
fprintf(fid, '    float sum = 0.0F;\n    float weight_sum = 0.0F;\n\n');
fprintf(fid, '    if ((vin_v != vin_v) || (vo_v != vo_v) || (icmd_a != icmd_a))\n');
fprintf(fid, '        return ZVS_T2_INVALID;\n');
fprintf(fid, '    iv = zvs_t2_axis_index(vin_v, zvs_t2_vin_axis, ZVS_T2_N_VIN, &fv);\n');
fprintf(fid, '    io = zvs_t2_axis_index(vo_v, zvs_t2_vo_axis, ZVS_T2_N_VO, &fo);\n');
fprintf(fid, '    ii = zvs_t2_axis_index(icmd_a, zvs_t2_icmd_axis, ZVS_T2_N_ICMD, &fi);\n\n');
fprintf(fid, '    zvs_t2_accumulate(zvs_t2_sample(iv, io, ii),\n');
fprintf(fid, '                      (1.0F - fv) * (1.0F - fo) * (1.0F - fi),\n');
fprintf(fid, '                      &sum, &weight_sum);\n');
fprintf(fid, '    zvs_t2_accumulate(zvs_t2_sample(iv, io, ii + 1U),\n');
fprintf(fid, '                      (1.0F - fv) * (1.0F - fo) * fi, &sum, &weight_sum);\n');
fprintf(fid, '    zvs_t2_accumulate(zvs_t2_sample(iv, io + 1U, ii),\n');
fprintf(fid, '                      (1.0F - fv) * fo * (1.0F - fi), &sum, &weight_sum);\n');
fprintf(fid, '    zvs_t2_accumulate(zvs_t2_sample(iv, io + 1U, ii + 1U),\n');
fprintf(fid, '                      (1.0F - fv) * fo * fi, &sum, &weight_sum);\n');
fprintf(fid, '    zvs_t2_accumulate(zvs_t2_sample(iv + 1U, io, ii),\n');
fprintf(fid, '                      fv * (1.0F - fo) * (1.0F - fi), &sum, &weight_sum);\n');
fprintf(fid, '    zvs_t2_accumulate(zvs_t2_sample(iv + 1U, io, ii + 1U),\n');
fprintf(fid, '                      fv * (1.0F - fo) * fi, &sum, &weight_sum);\n');
fprintf(fid, '    zvs_t2_accumulate(zvs_t2_sample(iv + 1U, io + 1U, ii),\n');
fprintf(fid, '                      fv * fo * (1.0F - fi), &sum, &weight_sum);\n');
fprintf(fid, '    zvs_t2_accumulate(zvs_t2_sample(iv + 1U, io + 1U, ii + 1U),\n');
fprintf(fid, '                      fv * fo * fi, &sum, &weight_sum);\n\n');
fprintf(fid, '    if (weight_sum < 0.999999F) return ZVS_T2_INVALID;\n');
fprintf(fid, '    return sum / weight_sum;\n}\n\n');

fprintf(fid, 'float ZVS_T2_LookupSeconds(float vin_v, float vo_v, float icmd_a)\n{\n');
fprintf(fid, '    float normalized = ZVS_T2_Lookup(vin_v, vo_v, icmd_a);\n');
fprintf(fid, '    if (normalized == ZVS_T2_INVALID) return ZVS_T2_INVALID;\n');
fprintf(fid, '    return normalized * ZVS_T2_SWITCH_PERIOD_S;\n}\n');
end

function writeVector(fid, name, values)
fprintf(fid, 'const float %s[%d] = {\n', name, numel(values));
for k = 1:numel(values)
    fprintf(fid, '    %s', cFloat(values(k)));
    if k < numel(values)
        fprintf(fid, ',');
    end
    if mod(k, 8) == 0
        fprintf(fid, '\n');
    else
        fprintf(fid, ' ');
    end
end
fprintf(fid, '};\n\n');
end

function value = cFloat(number)
value = sprintf('%.9g', double(number));
if isempty(strfind(value, '.')) && isempty(strfind(lower(value), 'e'))
    value = [value '.0']; %#ok<AGROW>
end
value = [value 'F']; %#ok<AGROW>
end
